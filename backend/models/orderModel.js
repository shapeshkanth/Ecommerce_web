import mongoose from "mongoose"

const orderModel = new mongoose.Schema({
    ShippingAddress:{
        Address:{
            type:String,
            required:true
        },
        city:{
            type:String,
            required:true
        },
        state:{
            type:String,
            required:true
        },
        country:{
            type:String,
            required:true
        },
        pincode:{
            type:Number,
            required:true
        },
        phoneNo:{
            type:Number,
            required:true
        }
    },
    OrderItems:[
        {
            name:{
                type:String,
                required:true
            },
            price:{
                type:Number,
                required:true
            },
            quantity:{
                type:String,
                required:true
            },
            image:{
                type:String,
                required:true
            },
            product:{
                type:mongoose.Schema.ObjectId,
                ref:"Product",
                required:true
            },

        }
    ],
    orderStatus:{
        type:String,
        required:true,
        default:"Processing"
    },
    user:{
        type:mongoose.Schema.ObjectId,
        ref:"User",
        required:true
    
    },
    paymentInfo:{ 
        id:{
            type:String,
            required:true
        },
        status:{
            type:String,
            required:true
        }
    },
    paidAt:{
        type:Date,
        required:true
    },
    price:{
        type:Number,
        required:true,
        default:0
    },
    tax:{
        type:Number,
        required:true,
        default:0
    },
    shippingPrice:{
        type:Number,
        required:true,
        default:0
    },
    TotalPrice:{
        type:Number,
        required:true,
        default:0
    },
    deliveryAt:Date,
    createAt:{
        type:Date,
        default:Date.now()
    }


})

export default mongoose.model("Order",orderModel)